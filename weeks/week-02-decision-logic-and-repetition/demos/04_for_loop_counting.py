"""
Week 2 Demo 4: for loop counting

Purpose:
Show repeated behavior with a clear range.

Instructor note:
Emphasize that range(1, 6) stops before 6. This is a good place to discuss
off-by-one confusion.
"""

print("Counting from 1 to 5:")

for number in range(1, 6):
    print(number)

print("Done counting.")

