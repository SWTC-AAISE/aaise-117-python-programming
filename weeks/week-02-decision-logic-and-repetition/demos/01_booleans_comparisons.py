"""
Week 2 Demo 1: booleans and comparisons

Purpose:
Show that comparisons produce True/False values that programs can use.

Instructor note:
Pause after each comparison and ask students to predict the result before
running the line.
"""

age = 18
minimum_age = 16

print("Age:", age)
print("Minimum age:", minimum_age)

is_old_enough = age >= minimum_age
print("Old enough:", is_old_enough)

score = 72
passing_score = 70

is_passing = score >= passing_score
print("Score:", score)
print("Passing:", is_passing)

